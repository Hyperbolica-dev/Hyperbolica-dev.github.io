export type BlogLocale = 'en' | 'zh';

export function localeFromPath(pathname: string): BlogLocale {
	return pathname === '/zh' || pathname.startsWith('/zh/') ? 'zh' : 'en';
}

export function pathForLocale(pathname: string, locale: BlogLocale): string {
	const unprefixed = pathname.replace(/^\/zh(?=\/|$)/, '') || '/';
	if (locale === 'en') return unprefixed;
	return unprefixed === '/' ? '/zh/' : `/zh${unprefixed}`;
}

